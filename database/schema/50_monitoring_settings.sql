CREATE TABLE monitoring_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_analysis_interval_sec INT NOT NULL,
    alert_analysis_interval_sec INT NOT NULL,
    verify_analysis_interval_sec INT NOT NULL,
    candidate_confidence_threshold DECIMAL(5,4) NOT NULL,
    candidate_min_detection_count INT NOT NULL,
    temporal_validation_sec INT NOT NULL,
    incident_confidence_threshold DECIMAL(5,4) NOT NULL,
    reconnect_interval_sec INT NOT NULL,
    max_reconnect_attempts INT NOT NULL,
    quality_threshold DECIMAL(5,4) NOT NULL,
    updated_by BIGINT REFERENCES users(id),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE monitoring_settings IS '감시·분석 기준';
COMMENT ON COLUMN monitoring_settings.id IS '감시 설정 ID';
COMMENT ON COLUMN monitoring_settings.base_analysis_interval_sec IS '기본 분석 주기(초)';
COMMENT ON COLUMN monitoring_settings.alert_analysis_interval_sec IS '특보 분석 주기(초)';
COMMENT ON COLUMN monitoring_settings.verify_analysis_interval_sec IS '집중 분석 주기(초)';
COMMENT ON COLUMN monitoring_settings.candidate_confidence_threshold IS '후보 신뢰도 임계값';
COMMENT ON COLUMN monitoring_settings.candidate_min_detection_count IS '후보 최소 탐지 횟수';
COMMENT ON COLUMN monitoring_settings.temporal_validation_sec IS '시간 연속성 검증 기준';
COMMENT ON COLUMN monitoring_settings.incident_confidence_threshold IS '사건 확정 신뢰도 임계값';
COMMENT ON COLUMN monitoring_settings.reconnect_interval_sec IS '재연결 주기(초)';
COMMENT ON COLUMN monitoring_settings.max_reconnect_attempts IS '최대 재연결 시도 횟수';
COMMENT ON COLUMN monitoring_settings.quality_threshold IS '영상 품질 임계값';
COMMENT ON COLUMN monitoring_settings.updated_by IS '수정 사용자 ID';
COMMENT ON COLUMN monitoring_settings.updated_at IS '수정 일시';
