CREATE TABLE route_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_version VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    agency_recommendation_id BIGINT NOT NULL REFERENCES incident_agency_recommendations(id)
);
COMMENT ON TABLE route_evaluations IS '경로 평가 실행';
COMMENT ON COLUMN route_evaluations.id IS '경로 평가 ID';
COMMENT ON COLUMN route_evaluations.rule_version IS '규칙 버전';
COMMENT ON COLUMN route_evaluations.created_at IS '생성 일시';
COMMENT ON COLUMN route_evaluations.agency_recommendation_id IS '기관 추천 ID';
