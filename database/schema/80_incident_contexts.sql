CREATE TABLE incident_contexts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    weather_alert_id BIGINT REFERENCES weather_alerts(id),
    rainfall_mm DECIMAL(7,2),
    water_level_m DECIMAL(7,2),
    traffic_level VARCHAR(30),
    blocked_lane_count INT,
    road_type VARCHAR(50),
    nearby_facility_type VARCHAR(100),
    nearby_facility_distance_m INT,
    past_disaster_count INT,
    raw_context_json JSON NOT NULL,
    captured_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE incident_contexts IS '외부 상황 스냅샷';
COMMENT ON COLUMN incident_contexts.id IS '외부 상황 스냅샷 ID';
COMMENT ON COLUMN incident_contexts.incident_id IS '사건 ID';
COMMENT ON COLUMN incident_contexts.weather_alert_id IS '기상특보 ID';
COMMENT ON COLUMN incident_contexts.rainfall_mm IS '강수량(mm)';
COMMENT ON COLUMN incident_contexts.water_level_m IS '수위(m)';
COMMENT ON COLUMN incident_contexts.traffic_level IS '교통 수준';
COMMENT ON COLUMN incident_contexts.blocked_lane_count IS '차단 차로 수';
COMMENT ON COLUMN incident_contexts.road_type IS '도로 유형';
COMMENT ON COLUMN incident_contexts.nearby_facility_type IS '인근 시설 유형';
COMMENT ON COLUMN incident_contexts.nearby_facility_distance_m IS '인근 시설 거리(m)';
COMMENT ON COLUMN incident_contexts.past_disaster_count IS '주변 지역 과거 재난 횟수';
COMMENT ON COLUMN incident_contexts.raw_context_json IS '외부 상황 원본 JSON';
COMMENT ON COLUMN incident_contexts.captured_at IS '수집 일시';
