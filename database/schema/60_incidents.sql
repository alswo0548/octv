CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_no VARCHAR(50) NOT NULL,
    cctv_id BIGINT NOT NULL REFERENCES cctvs(id),
    hazard_type VARCHAR(50) NOT NULL,
    confidence DECIMAL(5,4) NOT NULL,
    model_version VARCHAR(100) NOT NULL,
    detection_image_path VARCHAR(500) NOT NULL,
    detection_bbox_json JSON NOT NULL,
    detection_duration_sec INT NOT NULL,
    dedup_key VARCHAR(255) NOT NULL,
    status incident_status_enum NOT NULL DEFAULT 'DETECTED',
    detected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_detected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE incidents IS '확정 사건';
COMMENT ON COLUMN incidents.id IS '확정 사건 ID';
COMMENT ON COLUMN incidents.incident_no IS '사건 번호';
COMMENT ON COLUMN incidents.cctv_id IS 'CCTV ID';
COMMENT ON COLUMN incidents.hazard_type IS '재난 유형';
COMMENT ON COLUMN incidents.confidence IS '탐지 신뢰도';
COMMENT ON COLUMN incidents.model_version IS '모델 버전';
COMMENT ON COLUMN incidents.detection_image_path IS '탐지 이미지 경로';
COMMENT ON COLUMN incidents.detection_bbox_json IS '탐지 바운딩박스 JSON';
COMMENT ON COLUMN incidents.detection_duration_sec IS '탐지 지속시간(초)';
COMMENT ON COLUMN incidents.dedup_key IS '중복 판별 키';
COMMENT ON COLUMN incidents.status IS '사건 상태';
COMMENT ON COLUMN incidents.detected_at IS '탐지 일시';
COMMENT ON COLUMN incidents.last_detected_at IS '마지막 탐지 일시';
