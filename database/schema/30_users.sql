CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    role user_role_enum NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    agency_id BIGINT REFERENCES agencies(id),
    notification_enabled BOOLEAN NOT NULL DEFAULT TRUE
);
COMMENT ON TABLE users IS '관리자·출동요원';
COMMENT ON COLUMN users.id IS '사용자 ID';
COMMENT ON COLUMN users.email IS '이메일';
COMMENT ON COLUMN users.password_hash IS '비밀번호 해시';
COMMENT ON COLUMN users.name IS '이름';
COMMENT ON COLUMN users.role IS '역할';
COMMENT ON COLUMN users.is_active IS '활성 여부';
COMMENT ON COLUMN users.agency_id IS '기관 ID';
COMMENT ON COLUMN users.notification_enabled IS '알림 수신 여부';
