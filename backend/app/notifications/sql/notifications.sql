CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    read_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    incidents_id BIGINT NOT NULL REFERENCES incidents(id),
    agency_id BIGINT NOT NULL REFERENCES agencies(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    agency_recommendation_id BIGINT NOT NULL REFERENCES incident_agency_recommendations(id),
    CONSTRAINT uq_notifications_recommendation_user UNIQUE (agency_recommendation_id, user_id)
);
COMMENT ON TABLE notifications IS '사용자별 알림';
COMMENT ON COLUMN notifications.id IS '알림 ID';
COMMENT ON COLUMN notifications.read_at IS '읽은 일시';
COMMENT ON COLUMN notifications.created_at IS '생성 일시';
COMMENT ON COLUMN notifications.incidents_id IS '사건 ID · 원본 복수형 이름 유지';
COMMENT ON COLUMN notifications.agency_recommendation_id IS '기관 추천 ID';
COMMENT ON COLUMN notifications.agency_id IS '기관 ID';
COMMENT ON COLUMN notifications.user_id IS '사용자 ID';
