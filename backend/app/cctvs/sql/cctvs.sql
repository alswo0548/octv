CREATE TABLE cctvs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_cctv_id VARCHAR(100) NOT NULL,
    name VARCHAR(150) NOT NULL,
    provider VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    latitude DECIMAL(10,7) NOT NULL,
    longitude DECIMAL(10,7) NOT NULL,
    stream_url VARCHAR(500),
    is_monitored BOOLEAN NOT NULL DEFAULT FALSE,
    connection_status connection_status_enum NOT NULL DEFAULT 'DISCONNECTED',
    video_quality_status video_quality_enum,
    analysis_status analysis_status_enum,
    last_frame_at TIMESTAMP WITHOUT TIME ZONE,
    region_code VARCHAR(100) REFERENCES region(region_code),
    monitored_mode monitored_mode_enum,
    CONSTRAINT uq_cctvs_provider_external UNIQUE (provider, external_cctv_id)
);
COMMENT ON TABLE cctvs IS 'CCTV 기본정보·현재 상태';
COMMENT ON COLUMN cctvs.id IS 'CCTV ID';
COMMENT ON COLUMN cctvs.external_cctv_id IS '외부 CCTV ID';
COMMENT ON COLUMN cctvs.name IS 'CCTV명';
COMMENT ON COLUMN cctvs.provider IS '제공 기관';
COMMENT ON COLUMN cctvs.address IS '주소';
COMMENT ON COLUMN cctvs.latitude IS '위도';
COMMENT ON COLUMN cctvs.longitude IS '경도';
COMMENT ON COLUMN cctvs.stream_url IS '스트리밍 URL';
COMMENT ON COLUMN cctvs.is_monitored IS '상시 감시 여부';
COMMENT ON COLUMN cctvs.connection_status IS '연결 상태';
COMMENT ON COLUMN cctvs.video_quality_status IS '영상 품질 상태';
COMMENT ON COLUMN cctvs.analysis_status IS '분석 상태';
COMMENT ON COLUMN cctvs.last_frame_at IS '마지막 프레임 수신 일시';
COMMENT ON COLUMN cctvs.region_code IS '지역코드 ID';
COMMENT ON COLUMN cctvs.monitored_mode IS '현재 감시 상태';
