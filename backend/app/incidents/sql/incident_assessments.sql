CREATE TABLE incident_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    risk_score DECIMAL(6,2) NOT NULL,
    risk_level VARCHAR(30) NOT NULL,
    risk_breakdown_json JSON NOT NULL,
    priority_score DECIMAL(6,2) NOT NULL,
    priority VARCHAR(30) NOT NULL,
    priority_breakdown_json JSON NOT NULL,
    rule_version VARCHAR(50) NOT NULL
);
COMMENT ON TABLE incident_assessments IS '위험도·우선순위';
COMMENT ON COLUMN incident_assessments.id IS '위험도·우선순위 평가 ID';
COMMENT ON COLUMN incident_assessments.incident_id IS '사건 ID';
COMMENT ON COLUMN incident_assessments.risk_score IS '위험도 점수';
COMMENT ON COLUMN incident_assessments.risk_level IS '위험도 등급';
COMMENT ON COLUMN incident_assessments.risk_breakdown_json IS '위험도 세부 내역 JSON';
COMMENT ON COLUMN incident_assessments.priority_score IS '우선순위 점수';
COMMENT ON COLUMN incident_assessments.priority IS '대응 우선순위';
COMMENT ON COLUMN incident_assessments.priority_breakdown_json IS '우선순위 세부 내역 JSON';
COMMENT ON COLUMN incident_assessments.rule_version IS '규칙 버전';
