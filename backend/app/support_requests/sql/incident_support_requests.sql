CREATE TABLE incident_support_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    responder_id BIGINT NOT NULL REFERENCES users(id),
    support_type support_type_enum NOT NULL,
    request_content TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    agency_id BIGINT NOT NULL REFERENCES agencies(id)
);
COMMENT ON TABLE incident_support_requests IS '추가 지원 요청';
COMMENT ON COLUMN incident_support_requests.id IS '추가 지원 요청 ID';
COMMENT ON COLUMN incident_support_requests.incident_id IS '사건 ID';
COMMENT ON COLUMN incident_support_requests.responder_id IS '요청 작성 사용자 ID';
COMMENT ON COLUMN incident_support_requests.support_type IS '요청 지원 유형';
COMMENT ON COLUMN incident_support_requests.request_content IS '추가 지원 요청 내용';
COMMENT ON COLUMN incident_support_requests.created_at IS '요청 시각';
COMMENT ON COLUMN incident_support_requests.agency_id IS '기관 ID';
